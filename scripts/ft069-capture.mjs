 await page.waitForFunction(()=>{const s=document.querySelector("#agentSummary")?.textContent??"";return s.includes("Recommendation")&&s.includes("HOLD")},{timeout:30000});
 stamp("run_provider_result",t0);
 await page.screenshot({path:join(out,"run-provider-result.png")});
 await hold(8500);
