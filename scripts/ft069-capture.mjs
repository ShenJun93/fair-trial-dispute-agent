 stamp("financial_safety_boundary",t0);
 await page.screenshot({path:join(out,"financial-boundary.png")});
 await hold(5500);
 stamp("recording_end",t0);
 const video=page.video();
 const source=await video.path();
 await page.close();await ctx.close();ctx=null;
 const target=join(out,"raw-browser.webm");await rename(source,target);
 const sha=createHash("sha256").update(await readFile(target)).digest("hex");
