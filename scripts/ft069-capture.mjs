 stamp("explain_provider_result",t0);
 await page.screenshot({path:join(out,"explain-provider-result.png")});
 await hold(7000);
 await page.locator("#judgeRunLink").click();
 await page.locator("#agentScenario").selectOption("synthetic-high-fraud");
 stamp("run_synthetic_setup",t0);
 await page.screenshot({path:join(out,"run-synthetic-setup.png")});
 await hold(4000);
